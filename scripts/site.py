#!/usr/bin/env python3
"""Regenerate the feature list in README.md and site/index.html from docs/features.toml,
and the website's "What's new" box from the newest file in docs/releases/.

    python3 scripts/site.py           rewrite the generated blocks in place
    python3 scripts/site.py --check   change nothing; exit 1 if a block is out of date
    python3 scripts/site.py --list    print the features, one per line, for a quick look

Generated blocks sit between marker comments, and only the text between them is touched:

    README.md        <!-- features:start ... -->  ...  <!-- features:end -->
    site/index.html  <!-- features:start ... -->  ...  <!-- features:end -->
    site/index.html  <!-- whatsnew:start ... -->  ...  <!-- whatsnew:end -->
    README.md        <!-- clone:start ... -->     ...  <!-- clone:end -->

It also points every site link written as <a href="..." data-repo="docs/X.md"> at the
repository named by [project] repo in docs/features.toml (data-repo="" is the repository
itself), so moving the repository is a one-line edit there.

The feature file is validated first: known groups, a title and a one-sentence text,
status "have" or "soon", no em dashes, and every roadmap reference checked against
docs/ROADMAP.md (a "have" feature whose roadmap row is not [have] is an error, so the
list never claims something that is not built). Decision references ("D44") must name an
entry in docs/decisions.md.

Exit codes: 0 done (or up to date), 1 a block is out of date (--check only),
2 the feature file, a release note or a marker is wrong; nothing was written.

Python 3.11 or later (tomllib), standard library only. How the pieces fit together:
docs/WEBSITE.md.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 or older
    sys.stderr.write("site.py: needs Python 3.11 or later (tomllib)\n")
    sys.exit(2)

ROOT = Path(__file__).resolve().parent.parent
FEATURES = ROOT / "docs" / "features.toml"
ROADMAP = ROOT / "docs" / "ROADMAP.md"
DECISIONS = ROOT / "docs" / "decisions.md"
RELEASES = ROOT / "docs" / "releases"
README = ROOT / "README.md"
SITE = ROOT / "site" / "index.html"

STATUSES = ("have", "soon")
EM_DASH = "\u2014"
NOTE = "generated by scripts/site.py from {src}: edit that, then run python3 scripts/site.py"
VERSION_FILE = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.]+))?\.md$")
MAX_WHATSNEW_BULLETS = 6


class Invalid(Exception):
    """The input is wrong in a way a person has to fix."""


# ----------------------------------------------------------------------------- input


def load_features() -> tuple[dict, list[dict], list[dict]]:
    try:
        data = tomllib.loads(FEATURES.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise Invalid(f"{rel(FEATURES)} is missing")
    except tomllib.TOMLDecodeError as e:
        raise Invalid(f"{rel(FEATURES)}: {e}")

    project = data.get("project", {})
    groups = data.get("group", [])
    features = data.get("feature", [])
    problems: list[str] = []
    unknown_top = set(data) - {"project", "group", "feature"}
    if unknown_top:
        problems.append(f"unknown top-level keys: {', '.join(sorted(unknown_top))}")
    repo = project.get("repo") if isinstance(project, dict) else None
    if not isinstance(repo, str) or not re.fullmatch(r"https://[^\s\"'<>]+[^/\s\"'<>]", repo):
        problems.append("[project] repo must be an https URL with no trailing slash")
    elif set(project) - {"repo"}:
        problems.append(f"[project]: unknown keys {', '.join(sorted(set(project) - {'repo'}))}")

    ids = []
    for i, g in enumerate(groups, 1):
        where = f"group {i}"
        extra = set(g) - {"id", "title"}
        if extra:
            problems.append(f"{where}: unknown keys {', '.join(sorted(extra))}")
        if not isinstance(g.get("id"), str) or not re.fullmatch(r"[a-z][a-z0-9-]*", g["id"]):
            problems.append(f"{where}: id must be lowercase letters, digits and hyphens")
            continue
        if g["id"] in ids:
            problems.append(f"{where}: duplicate id {g['id']!r}")
        ids.append(g["id"])
        if not isinstance(g.get("title"), str) or not g["title"].strip():
            problems.append(f"{where} ({g['id']}): missing title")

    roadmap = roadmap_statuses()
    decisions = decision_numbers()
    titles = set()
    for i, f in enumerate(features, 1):
        where = f"feature {i} ({f.get('title', 'no title')!r})"
        extra = set(f) - {"group", "title", "text", "status", "ref"}
        if extra:
            problems.append(f"{where}: unknown keys {', '.join(sorted(extra))}")
        if f.get("group") not in ids:
            problems.append(f"{where}: group {f.get('group')!r} is not a [[group]] id")
        title = f.get("title")
        if not isinstance(title, str) or not title.strip():
            problems.append(f"{where}: missing title")
        elif title.rstrip().endswith("."):
            problems.append(f"{where}: title should not end with a period")
        elif title in titles:
            problems.append(f"{where}: duplicate title")
        else:
            titles.add(title)
        text = f.get("text")
        if not isinstance(text, str) or not text.strip():
            problems.append(f"{where}: missing text")
        elif not text.rstrip().endswith((".", "?", "!")):
            problems.append(f"{where}: text should be a sentence ending with a period")
        for field in ("title", "text"):
            if isinstance(f.get(field), str) and EM_DASH in f[field]:
                problems.append(f"{where}: {field} has an em dash")
            if isinstance(f.get(field), str) and f[field].count("`") % 2:
                problems.append(f"{where}: {field} has an unmatched backtick")
        status = f.get("status")
        if status not in STATUSES:
            problems.append(f"{where}: status must be one of {', '.join(STATUSES)}")
        refs = f.get("ref", [])
        if isinstance(refs, str):
            refs = [refs]
        if not isinstance(refs, list) or not all(isinstance(r, str) for r in refs):
            problems.append(f"{where}: ref must be a string or a list of strings")
            continue
        for r in refs:
            if re.fullmatch(r"\d+\.\d+", r):
                if roadmap is None:
                    continue
                if r not in roadmap:
                    problems.append(f"{where}: roadmap item {r} is not in docs/ROADMAP.md")
                elif status == "have" and roadmap[r] != "have":
                    problems.append(
                        f"{where}: marked have, but roadmap item {r} is [{roadmap[r]}]"
                    )
                elif status == "soon" and roadmap[r] == "have":
                    warn(f"{where}: marked soon, but roadmap item {r} is [have]; time to flip it?")
            elif re.fullmatch(r"D\d+", r):
                if decisions is not None and int(r[1:]) not in decisions:
                    problems.append(f"{where}: decision {r} is not in docs/decisions.md")
            else:
                problems.append(f"{where}: ref {r!r} is neither a roadmap item (1.12) nor a decision (D44)")

    if problems:
        raise Invalid(f"{rel(FEATURES)}:\n  " + "\n  ".join(problems))
    return project, groups, features


def roadmap_statuses() -> dict[str, str] | None:
    """Item number -> have/partial/missing, from the roadmap's tables. None if no roadmap."""
    try:
        text = ROADMAP.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    out = {}
    for line in text.splitlines():
        m = re.match(r"^\|\s*(\d+\.\d+)\s*\|", line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        status = [c for c in cells if re.fullmatch(r"\[(have|partial|missing)\]", c)]
        if status:
            out[m.group(1)] = status[-1][1:-1]
    return out


def decision_numbers() -> set[int] | None:
    try:
        text = DECISIONS.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    return {int(n) for n in re.findall(r"^## (\d+)\.", text, flags=re.M)}


def latest_release() -> tuple[str, Path] | None:
    """The newest docs/releases/<version>.md by version number (a prerelease sorts
    before its release). Other files there (templates, readmes) are ignored."""
    if not RELEASES.is_dir():
        return None
    best = None
    for p in RELEASES.iterdir():
        m = VERSION_FILE.match(p.name)
        if not m or not p.is_file():
            continue
        major, minor, patch, pre = m.groups()
        key = (int(major), int(minor), int(patch), pre is None, pre or "")
        if best is None or key > best[0]:
            best = (key, p.name[:-3], p)
    return None if best is None else (best[1], best[2])


def parse_release(path: Path) -> tuple[str, str, list[str]]:
    """Title, lede and bullets of a release note, loosely: the first `# ` heading, the
    first plain paragraph, and the first bullets under any `## ` heading."""
    title, lede, bullets = "", "", []
    paragraph: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("# ") and not title:
            title = line[2:].strip()
            continue
        if line.startswith(("- ", "* ")):
            if paragraph and not lede:
                lede = " ".join(paragraph)
            paragraph = []
            bullets.append(line[2:].strip())
            continue
        if not line or line.startswith("#") or line.startswith("<!--"):
            if paragraph and not lede:
                lede = " ".join(paragraph)
            paragraph = []
            continue
        if bullets and raw.startswith((" ", "\t")):
            bullets[-1] += " " + line  # a bullet's continuation line
            continue
        if not bullets:
            paragraph.append(line)
    if paragraph and not lede:
        lede = " ".join(paragraph)
    if EM_DASH in title + lede + "".join(bullets):
        raise Invalid(f"{rel(path)} has an em dash")
    return title, lede, bullets


# ----------------------------------------------------------------------------- render


def md_inline(text: str) -> str:
    return text  # README text is already Markdown (inline code only)


def html_inline(text: str, rich: bool = False) -> str:
    """Escape for HTML, then turn `code` into <code>. With rich, also **bold**,
    *italic* (marks dropped) and [text](url) (text only, never a link)."""
    out = html.escape(text, quote=False)
    if rich:
        out = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", out)
        out = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", out)
        out = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\1", out)
        out = re.sub(r"(?<!\w)_(?!\s)(.+?)(?<!\s)_(?!\w)", r"\1", out)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    return out


def by_group(groups, features, status):
    for g in groups:
        items = [f for f in features if f["group"] == g["id"] and f["status"] == status]
        if items:
            yield g, items


def readme_block(groups, features) -> list[str]:
    lines = []
    for g, items in by_group(groups, features, "have"):
        lines += [f"### {g['title']}", ""]
        lines += [f"- **{f['title']}.** {md_inline(f['text'])}" for f in items]
        lines.append("")
    soon = [f for f in features if f["status"] == "soon"]
    if soon:
        lines += ["### On the roadmap", ""]
        lines += [f"- **{f['title']}.** {md_inline(f['text'])}" for f in soon]
        lines.append("")
    return lines


def site_features_block(groups, features) -> list[str]:
    lines = ['<div class="groups">']
    for g, items in by_group(groups, features, "have"):
        gid = f"g-{g['id']}"
        lines.append(f'  <section class="group" aria-labelledby="{gid}">')
        lines.append(f'    <h3 id="{gid}">{html_inline(g["title"])}</h3>')
        lines.append('    <ul class="feats">')
        for f in items:
            lines.append(
                f"      <li><strong>{html_inline(f['title'])}</strong>"
                f" {html_inline(f['text'])}</li>"
            )
        lines.append("    </ul>")
        lines.append("  </section>")
    lines.append("</div>")
    soon = [f for f in features if f["status"] == "soon"]
    if soon:
        lines.append('<section class="soon" aria-labelledby="g-soon">')
        lines.append('  <h3 id="g-soon">On the roadmap</h3>')
        lines.append('  <ul class="feats">')
        for f in soon:
            lines.append(
                f"    <li><strong>{html_inline(f['title'])}</strong>"
                f" {html_inline(f['text'])}</li>"
            )
        lines.append("  </ul>")
        lines.append("</section>")
    return lines


def site_whatsnew_block() -> list[str]:
    found = latest_release()
    if found is None:
        return [
            '<p class="wn-ver">No release yet</p>',
            "<p>The first release is on its way. Until then you can build Method Budget "
            "from source; every feature above is in the code today.</p>",
        ]
    version, path = found
    title, lede, bullets = parse_release(path)
    lines = [f'<p class="wn-ver">{html_inline(title or "Method Budget " + version)}</p>']
    if lede:
        lines.append(f"<p>{html_inline(lede, rich=True)}</p>")
    if bullets:
        lines.append('<ul class="wn-list">')
        for b in bullets[:MAX_WHATSNEW_BULLETS]:
            lines.append(f"  <li>{html_inline(b, rich=True)}</li>")
        lines.append("</ul>")
    return lines


# ----------------------------------------------------------------------------- splice


def splice(text: str, name: str, body: list[str], src: str, where: Path) -> str:
    """Replace what sits between <!-- name:start ... --> and <!-- name:end --> with body,
    indented like the start marker. The start marker is rewritten too (it carries the
    'generated' note)."""
    pattern = re.compile(
        rf"^([ \t]*)<!-- {name}:start\b[^>]*-->\n.*?^[ \t]*<!-- {name}:end -->$",
        flags=re.M | re.S,
    )
    matches = list(pattern.finditer(text))
    if len(matches) != 1:
        raise Invalid(
            f"{rel(where)}: expected one <!-- {name}:start --> ... <!-- {name}:end --> pair,"
            f" found {len(matches)}"
        )
    m = matches[0]
    indent = m.group(1)
    out = [f"{indent}<!-- {name}:start ({NOTE.format(src=src)}) -->"]
    out += [(indent + line) if line else "" for line in body]
    out.append(f"{indent}<!-- {name}:end -->")
    return text[: m.start()] + "\n".join(out) + text[m.end():]


def repo_links(text: str, repo: str, where: Path) -> str:
    """Rewrite href on every <a href="..." data-repo="path"> to point into the repo."""

    def url(path: str) -> str:
        if not path:
            return repo
        if path.startswith("/") or ".." in path.split("/") or '"' in path:
            raise Invalid(f"{rel(where)}: bad data-repo path {path!r}")
        return f"{repo}/blob/main/{path}"

    def fix(m: re.Match) -> str:
        return f'href="{html.escape(url(m.group(2)))}"{m.group(1)}data-repo="{m.group(2)}"'

    if re.search(r'data-repo="[^"]*"', text) and not re.search(r'href="[^"]*"\s+data-repo=', text):
        raise Invalid(f"{rel(where)}: write data-repo right after href")
    return re.sub(r'href="[^"]*"(\s+)data-repo="([^"]*)"', fix, text)


def expected_files() -> dict[Path, str]:
    project, groups, features = load_features()
    repo = project["repo"]
    out = {}
    for path in (README, SITE):
        try:
            out[path] = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            raise Invalid(f"{rel(path)} is missing")
    out[README] = splice(
        out[README], "features", readme_block(groups, features), "docs/features.toml", README
    )
    out[README] = splice(
        out[README], "clone", ["```bash", f"git clone {repo}.git", "```"],
        "docs/features.toml", README,
    )
    out[SITE] = repo_links(out[SITE], repo, SITE)
    out[SITE] = splice(
        out[SITE], "features", site_features_block(groups, features), "docs/features.toml", SITE
    )
    out[SITE] = splice(
        out[SITE], "whatsnew", site_whatsnew_block(), "the newest docs/releases/*.md", SITE
    )
    return out


# ----------------------------------------------------------------------------- main


def rel(p: Path) -> str:
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def warn(msg: str) -> None:
    sys.stderr.write(f"site.py: warning: {msg}\n")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if anything is out of date")
    mode.add_argument("--list", action="store_true", help="print the features and exit")
    args = ap.parse_args(argv)

    try:
        if args.list:
            _, groups, features = load_features()
            titles = {g["id"]: g["title"] for g in groups}
            for f in features:
                refs = f.get("ref", [])
                refs = [refs] if isinstance(refs, str) else refs
                print(f"{f['status']:4}  {titles[f['group']]}: {f['title']}  [{', '.join(refs)}]")
            return 0
        files = expected_files()
    except Invalid as e:
        sys.stderr.write(f"site.py: {e}\n")
        return 2

    stale = [p for p, text in files.items() if p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            for p in stale:
                sys.stderr.write(f"site.py: {rel(p)} is out of date\n")
            sys.stderr.write(
                "site.py: run `python3 scripts/site.py` and commit the result"
                " (docs/WEBSITE.md)\n"
            )
            return 1
        print("site.py: README.md and site/index.html are up to date")
        return 0
    for p in stale:
        p.write_text(files[p], encoding="utf-8")
        print(f"wrote {rel(p)}")
    if not stale:
        print("site.py: nothing to change")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
